import {
  IsString,
  IsNotEmpty,
  IsOptional,
  IsUUID,
  IsBoolean,
} from 'class-validator';
import { TIME_SCHEDULING_CONSTANTS } from '../../../common/utils/time-of-day.util';

/** DTO for user chat messages sent to Genie Copilot. */
export class CopilotChatDto {
  @IsString()
  @IsNotEmpty()
  message: string;

  @IsOptional()
  @IsUUID()
  sessionId?: string;

  @IsOptional()
  @IsBoolean()
  autoApply?: boolean;
}

/** DTO for direct 1-click alternative swap on place card (Hybrid model). */
export class DirectSwapDto {
  @IsUUID()
  @IsNotEmpty()
  newPlaceId: string;
}

/** DTO for applying a confirmed Copilot proposal. */
export class ApplyProposalDto {
  @IsString()
  @IsNotEmpty()
  toolName: string;

  @IsNotEmpty()
  args: Record<string, unknown>;

  @IsOptional()
  @IsString()
  proposalId?: string;
}

/** Place alternative item returned for card quick pick popover. */
export interface AlternativePlaceItem {
  id: string;
  name: string;
  address: string;
  latitude: number;
  longitude: number;
  ratingAvg: number;
  reviewCount: number;
  priceLevel: string | null;
  imageUrl: string | null;
  categoryName: string;
  distanceKm?: number;
}

/** Result returned from executing a Copilot tool. */
export interface CopilotToolExecutionResult {
  toolName: string;
  success: boolean;
  message: string;
  errorCode?: 'NOT_FOUND' | 'CONFLICT' | 'BAD_REQUEST';
  data?: Record<string, unknown>;
}

/** Proposal generated by Copilot requiring user confirmation before mutation. */
export interface CopilotProposal {
  id: string;
  toolName: string;
  title: string;
  description: string;
  dayNumber?: number;
  fromPlaceId?: string;
  fromPlaceName?: string;
  fromPlaceCoordinates?: {
    latitude: number;
    longitude: number;
  };
  toPlaceId?: string;
  toPlaceName?: string;
  toPlaceRating?: number;
  toPlaceCategory?: string;
  toPlaceAddress?: string;
  toPlaceImageUrl?: string;
  toPlaceCoordinates?: {
    latitude: number;
    longitude: number;
  };
  status?: 'PENDING' | 'APPLIED' | 'REJECTED';
  swapDays?: {
    dayA: number;
    dayB: number;
  };
  args: Record<string, unknown>;
}

/** Final response shape returned to frontend Copilot drawer. */
export interface CopilotChatResponse {
  sessionId: string;
  reply: string;
  modified: boolean;
  action?: {
    type: 'CREATE_NEW_TRIP';
    destination: string;
  };
  appliedTool?: {
    name: string;
    args: Record<string, unknown>;
    resultMessage: string;
  };
  proposal?: CopilotProposal;
  itinerary?: unknown;
}

/** Historical message record returned to frontend. */
export interface CopilotMessageHistoryItem {
  id: string;
  sender: 'user' | 'agent';
  content: string;
  createdAt: string;
  toolCalls?: unknown;
  proposal?: CopilotProposal;
}

